/**
 * 任务形请求的**词形判据**（第二批计划 §2.2 的入口闸）。
 *
 * ============================================================================
 *  它决定"要不要签发一份任务授权"，因此它的失败方向很重要
 * ============================================================================
 * ```text
 * 误判成任务 ⇒ 一次多余的规划调用（有预算、有界、可查）—— 代价可回收
 * 误判成普通聊天 ⇒ 用户说"帮我整理一下这些文件"得到的是一句空话 —— 代价不可回收
 * ```
 * ⇒ 判据**偏宽**，但有两道硬闸挡在后面：
 * ```text
 * ① `CHARACTER_TASK_AUTONOMY_ENABLED` 代码缺省 **off** —— 不开就没有任务授权
 * ② 签发出来的授权只覆盖**装配层当时启用的能力** —— 关掉的能力连候选都不是
 * ```
 * ⚠️ 这个文件**不读环境、不读开关**：它只回答"这句话像不像一个任务"。
 *    能不能发任务授权是装配层的事（"判据"与"授权"分开，与 M4.5 同一条纪律）。
 */

/** 任务形标记（**偏宽**：宁可多问一次模型，也不要对一句明确的委托装没听见） */
export const TASK_MARKERS =
  /(帮我|给我|替我|帮忙|做一个|做一份|做一张|做一份|生成|创建一份|整理|汇总|统计|归总|填|改成|修改|更新|保存到|存到|存成|写一份|写个|导出|导成|转成|转换成|批量|任务|按.{0,12}(整理|分类|汇总|填|生成|导出))/i

/** 写动作词（与"本机绝对路径"同时出现时才够成任务形） */
export const TASK_WRITE_VERBS =
  /(写|存|保存|创建|新建|生成|导出|覆盖|修改|改|填|替换|追加)/i

/**
 * 这句话像不像一个任务？
 *
 * 两条路各自成立：
 * ```text
 * ① 出现任务形标记（"帮我整理一下这些文件"）
 * ② 出现本机绝对路径 **且** 出现写动作词（"把结果写到 C:\work\out.txt"）
 * ```
 * ⚠️ 第 ② 条的第二个条件是必要的：`C:\Windows\notepad.exe 为什么打不开` 里
 *    有一个绝对路径，但它是一个**问题**，不是一次委托 —— 播报它会让每一句
 *    提到路径的话都变成一次规划调用。
 */
export function looksLikeTask(text: string): boolean {
  const trimmed = text.trim()
  if (trimmed === '') return false
  if (TASK_MARKERS.test(trimmed)) return true
  const hasAbsolutePath = /(?:[A-Za-z]:[\\/]|\\\\)[^\s"'`「」『』]{1,200}/.test(trimmed)
  return hasAbsolutePath && TASK_WRITE_VERBS.test(trimmed)
}
