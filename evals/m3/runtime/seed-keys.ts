/**
 * Seed 的**键名清单** —— 评测里唯一允许"重复书写人设名"的地方。
 *
 * ============================================================================
 *  为什么这里要重复一遍名字，而不是从 seed.ts import
 * ============================================================================
 * `src/kernel/identity/seed.ts` 里的 `KNOWN_TRAITS` / `KNOWN_VALUES` /
 * `KNOWN_BOUNDARIES` 是**私有**的（只导出 `SEED_VERSION` 等少数符号）。
 * 那是刻意的：Seed 的内容定义不该被到处引用来做判断，
 * 否则"她是谁"就会在十几个地方各有一份解读。
 *
 * 但评测**必须**知道她有哪些倾向 —— 否则"trait alignment"就无从谈起，
 * 而要求评测去猜名字又等于让评测发明人格。
 *
 * 所以这里的做法是：**评测侧写一份清单，并在运行时对着真实 Seed 校验**。
 * 一旦 Seed 改了名字而这里没跟上，`identity-core` 套件的
 * `seed-traits-complete` 会立刻失败 —— 重复是有代价的，但代价是可见的，
 * 而不是悄悄漂移。
 *
 * （这份清单对应计划书第 14/16/17 节里"苏沐薇的已知人格表"。）
 */

